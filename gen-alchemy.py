"""Writes lean-alchemy-data.js: the server's authored reinforce chances for every elixir and lucky powder.

Reads the server's item data (UTF-16 tab files; the same columns apps/server/internal/game/item/alchemy/catalog.go reads).
The chance at plus P (0..11, 11 holds above) is byte (3 - P % 4) of parameter 2 + P // 4, as reinforce.go probability() does.
Run:  python gen-alchemy.py <textdata folder>
"""
import glob, json, sys
from pathlib import Path

folder = Path(sys.argv[1] if len(sys.argv) > 1 else r'C:\sroserver\opensro\apps\server\.generated\game-data\1.150\server\textdata')
ELIXIRS = {'weapon': (3675, 3679), 'shield': (3676, 3680), 'armor': (3677, 3681), 'accessory': (3678, 3682)}
rows = {}
for path in sorted(glob.glob(str(folder / 'itemdata_*.txt'))):
    for line in open(path, encoding='utf-16', errors='replace'):
        a = line.rstrip('\r\n').split('\t')
        if len(a) < 128 or a[0] != '1' or not a[2].startswith('ITEM_ETC_ARCHEMY_REINFORCE_'):
            continue
        params = [int(a[118 + 2 * i]) & 0xffffffff for i in range(5)]
        rows[int(a[1])] = (a[2], params)

def chances(params):
    return [params[1 + p // 4] >> ((3 - p % 4) * 8) & 255 for p in range(12)]

data = {'elixirs': {}, 'powders': {}, 'kinds': {k: list(v) for k, v in ELIXIRS.items()}}
for ids in ELIXIRS.values():
    for i in ids:
        data['elixirs'][i] = chances(rows[i][1])
for i in range(3683, 3707):
    data['powders'][i] = {'degree': rows[i][1][0], 'chances': chances(rows[i][1])}
text = ('// Generated by gen-alchemy.py from the server item data: the authored success chance of every reinforce elixir and lucky powder\n'
        '// at plus +0..+11 (the +11 value holds above), and the elixir ids of each gear kind. Do not edit by hand.\n'
        'const ALCHEMY_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')
Path(__file__).with_name('lean-alchemy-data.js').write_text(text, encoding='utf-8', newline='\n')
print('elixir 3675 weapon A:', data['elixirs'][3675]); print('elixir 3679 weapon B:', data['elixirs'][3679])
